package com.example.auth_service.dto;

import com.example.auth_service.model.ObjectType;
import lombok.Data;

import java.time.LocalDateTime;

/**
 * DTO для возврата детализированной информации об объекте недвижимости.
 *
 * <p>Используется для передачи клиенту полной информации об объекте,
 * включая его идентификатор, название, тип, родителя, дату создания,
 * а также информацию о создателе и ответственном пользователе.</p>
 */
@Data
public class ObjectResponseDto {

    /**
     * Уникальный идентификатор объекта недвижимости.
     * Используется для идентификации объекта в системе.
     */
    private Long id;

    /**
     * Название объекта недвижимости.
     * Используется для отображения пользователю и поиска объектов.
     */
    private String name;

    /**
     * Тип объекта недвижимости (например: ПРОЕКТ, ЗДАНИЕ, ЭТАЖ, КВАРТИРА).
     * Определяет категорию и иерархическую структуру объекта.
     */
    private ObjectType objectType;

    /**
     * Идентификатор родительского объекта.
     * Может быть null для объектов верхнего уровня.
     * Используется для построения иерархии объектов.
     */
    private Long parentId;

    /**
     * Дата и время создания объекта.
     * Используется для аудита и сортировки объектов.
     */
    private LocalDateTime createdAt;

    // ----------- Информация о пользователе, создавшем объект -----------

    /**
     * Идентификатор пользователя, создавшего объект.
     */
    private Long createdById;

    /**
     * Имя пользователя, создавшего объект.
     */
    private String createdByFirstName;

    /**
     * Фамилия пользователя, создавшего объект.
     */
    private String createdByLastName;

    // ----------- Информация об ответственном пользователе -----------

    /**
     * Идентификатор ответственного пользователя за объект.
     * Может быть null, если ответственный ещё не назначен.
     */
    private Long responsibleUserId;

    /**
     * Имя ответственного пользователя.
     */
    private String responsibleUserFirstName;

    /**
     * Фамилия ответственного пользователя.
     */
    private String responsibleUserLastName;

    /**
     * Роль ответственного пользователя (например: ПРОРАБ, ПОДРЯДЧИК).
     * Используется для разграничения прав и управления уведомлениями.
     */
    private String responsibleUserRole;
}
