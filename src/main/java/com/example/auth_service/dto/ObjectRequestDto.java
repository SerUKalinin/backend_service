package com.example.auth_service.dto;

import com.example.auth_service.model.ObjectType;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import lombok.Data;

/**
 * DTO для передачи данных при создании или обновлении объекта недвижимости.
 *
 * <p>Используется клиентом для передачи информации о новом объекте или изменениях
 * существующего объекта в систему управления недвижимостью.</p>
 */
@Data
public class ObjectRequestDto {

    /**
     * Название объекта недвижимости.
     * <p>Обязательное поле. Должно быть заполнено. Используется для идентификации
     * объекта пользователями и отображения в интерфейсе.</p>
     */
    @NotBlank(message = "Имя объекта не должно быть пустым")
    private String name;

    /**
     * Тип объекта недвижимости.
     * <p>Обязательное поле. Определяет категорию объекта, например: ПРОЕКТ, ЗДАНИЕ,
     * ЭТАЖ, КВАРТИРА и т.д. Используется для фильтрации и иерархической организации объектов.</p>
     */
    @NotNull(message = "Тип объекта не должен быть null")
    private ObjectType objectType;

    /**
     * Идентификатор родительского объекта.
     * <p>Необязательное поле. Если объект находится на верхнем уровне, может быть null.
     * Используется для построения иерархии объектов.</p>
     */
    private Long parentId;

    /**
     * Идентификатор пользователя, ответственного за объект.
     * <p>Необязательное поле. Может быть null, если ответственный пользователь
     * ещё не назначен. Используется для управления правами и уведомлениями по объекту.</p>
     */
    private Long responsibleUserId;
}
