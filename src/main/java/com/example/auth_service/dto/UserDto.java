package com.example.auth_service.dto;

import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.util.List;

/**
 * DTO для передачи информации о пользователе между слоями приложения.
 *
 * <p>Используется для отображения данных пользователя клиенту или передачи
 * информации между сервисами без раскрытия чувствительных данных (например, пароля).</p>
 */
@Data
@NoArgsConstructor
@AllArgsConstructor
public class UserDto {

    /**
     * Уникальный идентификатор пользователя в системе.
     * Используется для поиска и идентификации пользователя.
     */
    private Long id;

    /**
     * Имя пользователя для входа в систему.
     * Обязательное поле, не должно быть пустым или состоять только из пробелов.
     */
    private String username;

    /**
     * Электронная почта пользователя.
     * Должна быть корректным email. Используется для уведомлений и восстановления пароля.
     */
    private String email;

    /**
     * Имя пользователя.
     * Может быть пустым, используется для отображения в интерфейсе.
     */
    private String firstName;

    /**
     * Фамилия пользователя.
     * Может быть пустой, используется для отображения в интерфейсе.
     */
    private String lastName;

    /**
     * Список ролей пользователя в системе.
     * Определяет права и доступ пользователя к различным функциональным модулям.
     */
    private List<String> roles;

    /**
     * Статус активации пользователя.
     * true — пользователь активирован и может авторизоваться;
     * false — пользователь заблокирован и доступ запрещен.
     */
    private boolean active;
}
