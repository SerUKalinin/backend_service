package com.example.auth_service.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import lombok.Data;

/**
 * DTO для подтверждения сброса пароля пользователя.
 *
 * <p>Используется в запросах API при завершении процесса сброса пароля
 * с применением токена подтверждения, отправленного пользователю по электронной почте.</p>
 */
@Data
public class PasswordResetDto {

    /**
     * Токен подтверждения сброса пароля.
     *
     * <p>Выдаётся пользователю при запросе на восстановление пароля
     * и используется для подтверждения права на смену пароля.</p>
     */
    @NotBlank(message = "Токен не может быть пустым")
    private String token;

    /**
     * Новый пароль пользователя.
     *
     * <p>Должен соответствовать требованиям безопасности:
     * минимум 8 символов, наличие заглавных и строчных букв,
     * цифр и специальных символов.</p>
     */
    @NotBlank(message = "Новый пароль не может быть пустым")
    @Pattern(
            regexp = "^(?=.*[0-9])(?=.*[a-z])(?=.*[A-Z])(?=.*[!@#$%^&*()_+\\-=\\[\\]{}|;:,.<>?]).{8,}$",
            message = "Пароль должен содержать минимум 8 символов, включая заглавные и строчные буквы, цифры и специальные символы"
    )
    private String newPassword;
}
