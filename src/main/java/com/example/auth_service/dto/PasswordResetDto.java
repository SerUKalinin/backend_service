package com.example.auth_service.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import lombok.Data;

/**
 * DTO для запроса на сброс пароля пользователя.
 *
 * <p>Используется при подтверждении смены пароля с помощью
 * токена, выданного пользователю после запроса на восстановление.</p>
 */
@Data
public class PasswordResetDto {

    /**
     * Токен подтверждения сброса пароля.
     * Получается пользователем при запросе на восстановление пароля.
     * Обязательное поле, не может быть пустым.
     */
    @NotBlank(message = "Токен не может быть пустым")
    private String token;

    /**
     * Новый пароль пользователя.
     * Обязательное поле, должно соответствовать требованиям безопасности:
     * минимум 8 символов, хотя бы одна цифра, одна строчная буква,
     * одна заглавная буква и один специальный символ.
     */
    @NotBlank(message = "Новый пароль не может быть пустым")
    @Pattern(
            regexp = "^(?=.*[0-9])(?=.*[a-z])(?=.*[A-Z])(?=.*[!@#$%^&*()_+\\-=\\[\\]{}|;:,.<>?]).{8,}$",
            message = "Пароль должен содержать минимум 8 символов, включая заглавные и строчные буквы, цифры и специальные символы"
    )
    private String newPassword;
}
