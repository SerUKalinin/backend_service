package com.example.auth_service.model;

/**
 * Перечисление {@code ObjectType} определяет все возможные типы объектов в системе управления
 * строительными проектами и недвижимостью.
 *
 * <p>Используется для классификации объектов в иерархии, определения правил валидации,
 * отображения и обработки задач, связанных с конкретными типами объектов.</p>
 */
public enum ObjectType {

    /** Здание — основной объект, содержащий подъезды и этажи. */
    BUILDING,

    /** Подъезд здания, объединяющий несколько этажей. */
    ENTRANCE,

    /** Цокольный этаж здания. */
    BASEMENT_FLOOR,

    /** Этаж здания. */
    FLOOR,

    /** Лестничный пролет на этаже или между этажами. */
    STAIRWELL,

    /** Лифт на этаже. */
    ELEVATOR,

    /** Балкон на этаже здания. */
    FLOOR_BALCONY,

    /** Коридор на этаже или в подъезде. */
    CORRIDOR,

    /** Холл лифта на этаже. */
    ELEVATOR_HALL,

    /** Жилая квартира, состоящая из комнат и балконов. */
    APARTMENT,

    /** Балкон квартиры. */
    APARTMENT_BALCONY,

    /** Комната внутри квартиры. */
    ROOM,

    /** Задача, связанная с объектом недвижимости (ремонт, дефекты, проверки). */
    TASK
}
