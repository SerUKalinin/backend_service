package com.example.auth_service.model;

/**
 * Перечисление, определяющее возможные статусы задачи в системе.
 *
 * <p>Используется для отслеживания состояния выполнения задач и
 * управления бизнес-логикой, связанной с обработкой задач.</p>
 */
public enum TaskStatus {

    /** Задача только создана, ещё не начата. */
    NEW,

    /** Задача в процессе выполнения ответственным пользователем. */
    IN_PROGRESS,

    /** Задача просрочена, дедлайн истёк, но не завершена. */
    EXPIRED,

    /** Задача требует немедленного выполнения. */
    URGENT,

    /** Задача выполнена и закрыта. */
    COMPLETED
}
