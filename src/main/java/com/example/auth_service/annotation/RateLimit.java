package com.example.auth_service.annotation;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Аннотация для ограничения частоты вызовов методов API.
 *
 * Применяется на уровне контроллеров и сервисов для защиты
 * чувствительных эндпоинтов от избыточной нагрузки, брутфорса
 * или злоупотреблений. Подразумевает использование внешнего
 * хранилища (например, Redis) для учёта количества запросов.
 */
@Target(ElementType.METHOD)
@Retention(RetentionPolicy.RUNTIME)
public @interface RateLimit {

    /**
     * Максимальное количество разрешённых вызовов метода
     * за указанный временной интервал.
     *
     * @return число запросов, которое нельзя превысить
     */
    int limit() default 10;

    /**
     * Временной интервал (окно) для применения ограничения.
     *
     * Указывает продолжительность окна в секундах, в течение
     * которого считается количество вызовов метода.
     *
     * @return длительность окна в секундах
     */
    int timeWindow() default 60;

    /**
     * Ключ для идентификации лимита в хранилище.
     *
     * Может быть указан явно для общих или кастомных лимитов.
     * Если ключ не задан, он формируется автоматически на основе
     * контекста запроса (класс, метод, IP клиента).
     *
     * @return строка ключа для хранения данных о лимите
     */
    String key() default "";
}
